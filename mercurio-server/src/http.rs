//! Plain HTTP served by WebSocket listeners next to MQTT: static files,
//! such as a browser client's page, as mosquitto's `http_dir` does, and the
//! health and metrics endpoints.

use std::{
    future::Future,
    io,
    path::{Component, Path, PathBuf},
    pin::Pin,
    task::{Context, Poll},
};

use tokio::{
    fs::File,
    io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt, ReadBuf},
    sync::Semaphore,
    time::Duration,
};

/// Longest request head read before giving up on the request
const MAX_HEAD: usize = 8192;

/// How long answering one request may take, the file sent included. Kept
/// apart from the connect deadline, which only covers reading the request.
pub(crate) const RESPONSE_TIMEOUT: Duration = Duration::from_secs(60);

/// Responses one listener sends at once; further requests are answered
/// with Service Unavailable.
pub(crate) const MAX_RESPONSES: usize = 32;

/// What a listener answers plain HTTP requests with, and the responses it
/// may send at once.
pub(crate) struct Site {
    /// Where its files are, if it serves any
    pub dir: Option<PathBuf>,
    /// Whether it answers `GET /healthz`
    pub health: bool,
    /// Whether it answers `GET /metrics`
    pub metrics: bool,
    pub responses: Semaphore,
}

impl Site {
    pub(crate) fn new(dir: Option<PathBuf>, health: bool, metrics: bool) -> Self {
        Site {
            dir,
            health,
            metrics,
            responses: Semaphore::new(MAX_RESPONSES),
        }
    }

    /// The endpoint `target` names, if the listener serves it.
    fn endpoint(&self, target: &str) -> Option<Endpoint> {
        match target.split(['?', '#']).next()? {
            "/healthz" if self.health => Some(Endpoint::Health),
            "/metrics" if self.metrics => Some(Endpoint::Metrics),
            _ => None,
        }
    }
}

/// An answer generated by the broker rather than read from a file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Endpoint {
    Health,
    Metrics,
}

/// A generated response.
pub(crate) struct Page {
    pub status: &'static str,
    pub content_type: &'static str,
    pub body: String,
}

/// The request at the start of a WebSocket listener's connection.
pub(crate) enum Request<S> {
    /// A WebSocket upgrade to complete, with the bytes read so far replayed
    Upgrade(Rewind<S>),
    /// A plain HTTP request, with its head, to answer from the site
    Plain(S, String),
}

/// Reads the HTTP request head at the start of `stream`.
pub(crate) async fn read_request<S>(mut stream: S) -> io::Result<Request<S>>
where
    S: AsyncRead + Unpin,
{
    let mut head = Vec::new();
    while !head.windows(4).any(|w| w == b"\r\n\r\n") {
        if head.len() >= MAX_HEAD {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "request head too long",
            ));
        }
        let mut chunk = [0u8; 1024];
        let read = stream.read(&mut chunk).await?;
        if read == 0 {
            return Err(io::ErrorKind::UnexpectedEof.into());
        }
        head.extend_from_slice(&chunk[..read]);
    }

    let text = String::from_utf8_lossy(&head).into_owned();
    let upgrade = text
        .to_ascii_lowercase()
        .lines()
        .any(|line| line.starts_with("upgrade:") && line.contains("websocket"));
    if upgrade {
        return Ok(Request::Upgrade(Rewind::new(stream, head)));
    }
    Ok(Request::Plain(stream, text))
}

/// Answers the plain HTTP request `head` from `site`, if the listener may
/// send another response, with `page` generating the endpoints' answers.
pub(crate) async fn respond<S, F>(
    mut stream: S,
    head: &str,
    site: &Site,
    page: impl FnOnce(Endpoint) -> F,
) -> io::Result<()>
where
    S: AsyncWrite + Unpin,
    F: Future<Output = Page>,
{
    let Ok(_response) = site.responses.try_acquire() else {
        stream.write_all(&status("503 Service Unavailable")).await?;
        return stream.shutdown().await;
    };
    let mut words = head.split_whitespace();
    let (method, target) = (words.next().unwrap_or(""), words.next().unwrap_or(""));
    let found = match (method, site.endpoint(target), &site.dir) {
        ("GET" | "HEAD", Some(endpoint), _) => Found::Page(page(endpoint).await),
        ("GET" | "HEAD", None, Some(dir)) => find(dir, target).await,
        ("GET" | "HEAD", None, None) => Found::Status("404 Not Found"),
        _ => Found::Status("405 Method Not Allowed"),
    };
    match found {
        Found::Page(page) => {
            let header = format!(
                "HTTP/1.1 {}\r\nContent-Type: {}\r\nContent-Length: {}\r\n\
                 Connection: close\r\n\r\n",
                page.status,
                page.content_type,
                page.body.len(),
            );
            stream.write_all(header.as_bytes()).await?;
            if method == "GET" {
                stream.write_all(page.body.as_bytes()).await?;
            }
        }
        Found::File(file, path, length) => {
            let header = format!(
                "HTTP/1.1 200 OK\r\nContent-Type: {}\r\nContent-Length: {length}\r\n\
                 Connection: close\r\n\r\n",
                content_type(&path),
            );
            stream.write_all(header.as_bytes()).await?;
            if method == "GET" {
                tokio::io::copy(&mut file.take(length), &mut stream).await?;
            }
        }
        Found::Redirect(location) => {
            let response = format!(
                "HTTP/1.1 301 Moved Permanently\r\nLocation: {location}\r\n\
                 Content-Length: 0\r\nConnection: close\r\n\r\n"
            );
            stream.write_all(response.as_bytes()).await?;
        }
        Found::Status(code) => stream.write_all(&status(code)).await?,
    }
    stream.shutdown().await
}

/// What a request's target names.
enum Found {
    /// A file, its path and length
    File(File, PathBuf, u64),
    /// A directory named without its trailing slash: where it is
    Redirect(String),
    Status(&'static str),
    Page(Page),
}

async fn find(dir: &Path, target: &str) -> Found {
    let not_found = Found::Status("404 Not Found");
    let Some(path) = file_path(dir, target) else {
        return not_found;
    };
    let Ok(metadata) = tokio::fs::metadata(&path).await else {
        return not_found;
    };
    if metadata.is_dir() {
        return match redirect(target) {
            Some(location) => Found::Redirect(location),
            None => not_found,
        };
    }
    if !metadata.is_file() {
        return not_found;
    }
    match File::open(&path).await {
        Ok(file) => Found::File(file, path, metadata.len()),
        Err(_) => not_found,
    }
}

/// Where a directory named by `target` is, with its trailing slash and
/// query. Rebuilt from the path's segments, so `//host` can't send the
/// client to another host. None when `target` had the slash already.
fn redirect(target: &str) -> Option<String> {
    let (path, query) = match target.split_once('?') {
        Some((path, query)) => (path, Some(query)),
        None => (target, None),
    };
    if path.ends_with('/') {
        return None;
    }
    let mut location = String::from("/");
    for segment in path.split('/').filter(|s| !s.is_empty()) {
        location.push_str(segment);
        location.push('/');
    }
    if let Some(query) = query {
        location.push('?');
        location.push_str(query);
    }
    Some(location)
}

/// The file `target` names under `dir`, `index.html` for targets ending in
/// a slash. `None` for targets that would leave `dir`.
fn file_path(dir: &Path, target: &str) -> Option<PathBuf> {
    let path = target.split(['?', '#']).next()?;
    let relative = Path::new(path.trim_start_matches('/'));
    if !relative
        .components()
        .all(|c| matches!(c, Component::Normal(_)))
    {
        return None;
    }
    let mut file = dir.join(relative);
    if path.ends_with('/') {
        file.push("index.html");
    }
    Some(file)
}

fn content_type(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()) {
        Some("html" | "htm") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript",
        Some("css") => "text/css",
        Some("json") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("ico") => "image/x-icon",
        Some("wasm") => "application/wasm",
        Some("txt") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn status(status: &str) -> Vec<u8> {
    format!("HTTP/1.1 {status}\r\nContent-Length: 0\r\nConnection: close\r\n\r\n").into_bytes()
}

/// A stream whose first bytes, already read from it, are read again.
pub(crate) struct Rewind<S> {
    stream: S,
    prefix: Vec<u8>,
    position: usize,
}

impl<S> Rewind<S> {
    pub(crate) fn new(stream: S, prefix: Vec<u8>) -> Self {
        Self {
            stream,
            prefix,
            position: 0,
        }
    }
}

impl<S: AsyncRead + Unpin> AsyncRead for Rewind<S> {
    fn poll_read(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buf: &mut ReadBuf<'_>,
    ) -> Poll<io::Result<()>> {
        if self.position < self.prefix.len() {
            let rest = &self.prefix[self.position..];
            let len = rest.len().min(buf.remaining());
            buf.put_slice(&rest[..len]);
            self.position += len;
            return Poll::Ready(Ok(()));
        }
        Pin::new(&mut self.stream).poll_read(cx, buf)
    }
}

impl<S: AsyncWrite + Unpin> AsyncWrite for Rewind<S> {
    fn poll_write(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buf: &[u8],
    ) -> Poll<io::Result<usize>> {
        Pin::new(&mut self.stream).poll_write(cx, buf)
    }

    fn poll_flush(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        Pin::new(&mut self.stream).poll_flush(cx)
    }

    fn poll_shutdown(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        Pin::new(&mut self.stream).poll_shutdown(cx)
    }
}

#[cfg(test)]
mod tests {
    use super::{file_path, redirect, respond, Page, Site};
    use std::path::Path;

    async fn answer(site: &Site, head: &str) -> String {
        let mut out = Vec::new();
        respond(&mut out, head, site, |endpoint| async move {
            Page {
                status: "200 OK",
                content_type: "text/plain",
                body: format!("{endpoint:?}"),
            }
        })
        .await
        .unwrap();
        String::from_utf8(out).unwrap()
    }

    #[tokio::test]
    async fn test_endpoints_are_routed_by_path() {
        let site = Site::new(None, true, false);
        let health = answer(&site, "GET /healthz?probe=1 HTTP/1.1\r\n\r\n").await;
        assert!(health.starts_with("HTTP/1.1 200 OK\r\n"), "{health}");
        assert!(health.ends_with("\r\n\r\nHealth"), "{health}");
        let head = answer(&site, "HEAD /healthz HTTP/1.1\r\n\r\n").await;
        assert!(head.contains("Content-Length: 6\r\n"), "{head}");
        assert!(head.ends_with("\r\n\r\n"), "{head}");
        let post = answer(&site, "POST /healthz HTTP/1.1\r\n\r\n").await;
        assert!(post.starts_with("HTTP/1.1 405"), "{post}");
        let metrics = answer(&site, "GET /metrics HTTP/1.1\r\n\r\n").await;
        assert!(metrics.starts_with("HTTP/1.1 404"), "{metrics}");
    }

    #[test]
    fn test_paths_stay_inside_the_directory() {
        let dir = Path::new("/srv/www");
        assert_eq!(
            file_path(dir, "/app.js?v=2"),
            Some(Path::new("/srv/www/app.js").into())
        );
        assert_eq!(
            file_path(dir, "/docs/"),
            Some(Path::new("/srv/www/docs/index.html").into())
        );
        assert_eq!(file_path(dir, "/../etc/passwd"), None);
        assert_eq!(file_path(dir, "/a/../../etc/passwd"), None);
        assert_eq!(
            file_path(dir, "//etc/passwd"),
            Some(Path::new("/srv/www/etc/passwd").into())
        );
    }

    #[test]
    fn test_redirects_stay_on_this_host() {
        assert_eq!(redirect("/docs").as_deref(), Some("/docs/"));
        assert_eq!(redirect("/a//b?x=1").as_deref(), Some("/a/b/?x=1"));
        assert_eq!(
            redirect("//evil.example").as_deref(),
            Some("/evil.example/")
        );
        assert_eq!(redirect("").as_deref(), Some("/"));
        assert_eq!(redirect("/docs/"), None);
    }
}
